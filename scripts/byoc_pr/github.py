"""Clone the target repository, push one branch per endpoint and open (or reuse) its PR.

All commands go through ``git`` and the ``gh`` CLI with argument lists (no shell). The PR body
and commit message are passed on stdin. Neither ever contains the RabbitMQ password, which
only reaches the repository inside the vault-encrypted ``secret_group_vars/pulsar.yml``.
"""

from __future__ import annotations

import json
import subprocess
from collections.abc import Callable
from pathlib import Path

from scripts.byoc_pr.endpoint import Endpoint

Runner = Callable[..., str]


class CommandError(RuntimeError):
    """A git or gh command failed."""


def run(args: list[str], *, cwd: Path | None = None, input: str | None = None) -> str:
    result = subprocess.run(  # noqa: S603 - fixed argument lists, no shell
        args, cwd=cwd, input=input, capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        detail = result.stderr.strip()[-500:]
        raise CommandError(f"{' '.join(args[:2])} failed (exit {result.returncode}): {detail}")
    return result.stdout


def pr_title(endpoints: list[Endpoint]) -> str:
    plural = "s" if len(endpoints) > 1 else ""
    return f"Add BYOC pulsar endpoint{plural} {', '.join(e.id for e in endpoints)}"


def _endpoint_section(endpoint: Endpoint) -> str:
    request = endpoint.request
    return f"""Requested by Galaxy user: `{request.galaxy_username}`

- `distributed_compute` option `{endpoint.tag}` ("{endpoint.label}")
- TPV destination `{endpoint.destination}` (runner `{endpoint.runner}`): \
{request.max_accepted_cores} cores, {request.max_accepted_mem} GB memory, \
{request.min_accepted_gpus}-{request.max_accepted_gpus} GPUs
- RabbitMQ user `{endpoint.mq_user}` on vhost `{endpoint.vhost}`
- `{endpoint.password_var}` in `secret_group_vars/pulsar.yml` (Ansible Vault)
"""


def pr_body(endpoints: list[Endpoint]) -> str:
    """Description in the style of the usegalaxy.eu PRs: no password, no email."""
    what = "Pulsar endpoints" if len(endpoints) > 1 else "a Pulsar endpoint"
    sections = "\n".join(_endpoint_section(endpoint) for endpoint in endpoints)
    return f"""Hello,

This PR adds Bring Your Own Compute (BYOC) {what}, requested through the
"Bring your own Pulsar endpoint" (`byoc_pulsar`) user preference form.

{sections}
The message queue passwords are the ones the users entered in the form; they are only stored \
vault-encrypted and are not part of this description.

Generated by `scripts/byoc_pr` (src-component-galaxy-amqp).
"""


def commit_message(endpoints: list[Endpoint]) -> str:
    users = ", ".join(e.request.galaxy_username for e in endpoints)
    plural = "s" if len(endpoints) > 1 else ""
    requested = f"Requested by Galaxy user{plural} {users} via the byoc_pulsar form."
    return f"{pr_title(endpoints)}\n\n{requested}\n"


class GitHub:
    def __init__(self, repo: str, base: str, workdir: Path, runner: Runner = run) -> None:
        self.repo = repo
        self.base = base
        self.workdir = workdir
        self._run = runner

    def git(self, *args: str, input: str | None = None) -> str:
        return self._run(["git", *args], cwd=self.workdir, input=input)

    def checkout_base(self) -> None:
        """Clone (or refresh) the target repository and check out ``origin/<base>``."""
        if (self.workdir / ".git").is_dir():
            self.git("fetch", "--quiet", "origin", self.base)
        else:
            self._run(["gh", "repo", "clone", self.repo, str(self.workdir), "--", "--quiet"])
        self.git("checkout", "--quiet", "--detach", f"origin/{self.base}")

    def open_pr_url(self, branch: str) -> str | None:
        repo, state = ["--repo", self.repo], ["--state", "open", "--json", "url"]
        out = self._run(["gh", "pr", "list", *repo, "--head", branch, *state])
        found = json.loads(out or "[]")
        return found[0]["url"] if found else None

    def branch_exists(self, branch: str) -> bool:
        return bool(self.git("ls-remote", "--heads", "origin", branch).strip())

    def publish(self, endpoint: Endpoint, changes: dict[str, str]) -> str:
        """Commit ``changes`` on ``byoc/<id>`` from ``origin/<base>``, push, open the PR."""
        branch = endpoint.branch
        self.git("checkout", "--quiet", "-B", branch, f"origin/{self.base}")
        for path, text in changes.items():
            (self.workdir / path).parent.mkdir(parents=True, exist_ok=True)
            (self.workdir / path).write_text(text, encoding="utf-8")
        self.git("add", "--", *changes)
        self.git("commit", "--quiet", "-F", "-", input=commit_message([endpoint]))
        self.git("push", "--quiet", "origin", f"HEAD:refs/heads/{branch}")
        refs = ["--base", self.base, "--head", branch]
        text = ["--title", pr_title([endpoint]), "--body-file", "-"]
        url = self._run(
            ["gh", "pr", "create", "--repo", self.repo, *refs, *text], input=pr_body([endpoint])
        )
        self.git("checkout", "--quiet", "--detach", f"origin/{self.base}")
        return url.strip()
